"""AI Service for Google Gemini API integration.

Encapsulates all communication with the Google GenAI SDK.
Ensures API keys remain server-side and translates raw SDK objects into clean text.
"""
import logging
from google import genai
from google.genai.errors import APIError
from app.config import settings

logger = logging.getLogger(__name__)


def generate_ai_response(prompt: str) -> str:
    """Send a prompt to the Google Gemini model and return the clean text response.
    
    Args:
        prompt: User or system prompt text to send to Gemini.
        
    Returns:
        Clean string response generated by the model.
        
    Raises:
        ValueError: If GEMINI_API_KEY is missing or unconfigured.
        RuntimeError: If Gemini API fails, returns an empty response, or network error occurs.
    """
    api_key = settings.GEMINI_API_KEY.strip() if settings.GEMINI_API_KEY else ""

    if not api_key:
        raise ValueError(
            "GEMINI_API_KEY is not configured on the server. "
            "Please provide a valid Gemini API key in your backend .env file."
        )

    try:
        # Initialize Google GenAI client with server-side API key
        client = genai.Client(api_key=api_key)

        # Call Gemini model
        response = client.models.generate_content(
            model=settings.GEMINI_MODEL,
            contents=prompt
        )

        # Validate that model produced text
        if not response or not response.text:
            raise RuntimeError("Gemini model returned an empty or unusable response.")

        return response.text.strip()

    except ValueError:
        raise
    except APIError as e:
        logger.error(f"Gemini API error occurred: {e}")
        # Sanitize error: do not expose raw tokens or sensitive headers
        err_msg = getattr(e, "message", None) or "Upstream Gemini API rejected the request."
        raise RuntimeError(f"Gemini API Error: {err_msg}")
    except Exception as e:
        logger.error(f"Unexpected error communicating with Gemini: {e}")
        raise RuntimeError(f"Failed to communicate with AI provider: {str(e)}")
